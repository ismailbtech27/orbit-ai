import { useEffect, useState } from 'react';
import { apiService } from '../services/apiService';
import { ShieldAlert, AlertTriangle } from 'lucide-react';

export default function Alerts() {
  const [alerts, setAlerts] = useState([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    async function loadAlerts() {
      try {
        const data = await apiService.getAlerts();
        // Sort by most critical severity first, then by timestamp
        const severityWeight = { Critical: 4, High: 3, Medium: 2, Low: 1 };
        
        data.sort((a, b) => {
          if (severityWeight[b.severity] !== severityWeight[a.severity]) {
            return severityWeight[b.severity] - severityWeight[a.severity];
          }
          return new Date(b.timestamp) - new Date(a.timestamp);
        });
        
        setAlerts(data);
      } catch (e) {
        console.error(e);
      } finally {
        setLoading(false);
      }
    }
    loadAlerts();
    
    const interval = setInterval(loadAlerts, 5000);
    return () => clearInterval(interval);
  }, []);

  if (loading && alerts.length === 0) return <div style={{ padding: '2rem', textAlign: 'center', color: 'var(--text-muted)' }}>Loading active threat alerts...</div>;

  return (
    <div>
      <div className="flex-row justify-between" style={{ alignItems: 'flex-start', marginBottom: '2rem' }}>
        <div>
          <h2>Active Incident Queue</h2>
          <p className="text-muted">
            Security alerts generated by the ML Detection Engine, prioritized by severity.
          </p>
        </div>
      </div>

      <div className="card" style={{ padding: 0, overflow: 'hidden' }}>
        <div style={{ padding: '1.5rem', borderBottom: '1px solid var(--border-color)', display: 'flex', alignItems: 'center', gap: '0.75rem', backgroundColor: 'rgba(255,255,255,0.01)' }}>
             <ShieldAlert size={18} color="var(--critical-color)" />
             <h3 style={{ margin: 0 }}>Incident Backlog</h3>
        </div>
        <div className="table-container">
            <table>
              <thead>
                <tr>
                  <th>Incident ID</th>
                  <th>Timestamp</th>
                  <th>Threat Vector</th>
                  <th>Origin IP</th>
                  <th>Current Stage</th>
                  <th>Predicted Stage</th>
                  <th>Risk</th>
                  <th>Confidence</th>
                  <th>Deviation</th>
                  <th>Status</th>
                </tr>
              </thead>
              <tbody>
                {alerts.map((alert, index) => (
                  <tr key={alert.alertId}>
                    <td style={{ fontFamily: 'monospace', fontSize: '0.8rem', color: 'var(--text-muted)' }}>{alert.alertId.substring(0, 8)}...</td>
                    <td style={{ color: 'var(--text-muted)' }}>{new Date(alert.timestamp).toLocaleString()}</td>
                    <td style={{ fontWeight: 500 }}>{alert.threatType}</td>
                    <td style={{ fontFamily: 'monospace', color: 'var(--info-color)' }}>{alert.sourceIp}</td>
                    <td>{alert.currentStage || 'N/A'}</td>
                    <td>{alert.predictedStage || 'N/A'}</td>
                    <td>
                      <span className={`badge badge-${alert.severity.toLowerCase()}`}>
                        {alert.severity} ({alert.riskScore || 0})
                      </span>
                    </td>
                    <td><span style={{ color: 'var(--critical-color)', fontWeight: 600 }}>{alert.mlConfidence ? `${alert.mlConfidence}%` : 'N/A'}</span></td>
                    <td>
                       {alert.pathDeviationDetected ? (
                           <span className="badge" style={{ backgroundColor: 'rgba(234, 179, 8, 0.2)', color: 'var(--medium-color)' }}>Yes</span>
                       ) : (
                           <span className="badge" style={{ backgroundColor: 'rgba(255, 255, 255, 0.1)' }}>No</span>
                       )}
                    </td>
                    <td>
                        <span className={`badge ${alert.status === 'OPEN' ? 'badge-high' : alert.status === 'SIMULATED' ? 'badge-success' : 'badge-neutral'}`}>
                            {alert.status}
                        </span>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
        </div>
        
        {alerts.length === 0 && (
          <div style={{ textAlign: 'center', padding: '3rem', color: 'var(--text-muted)', display: 'flex', flexDirection: 'column', alignItems: 'center', gap: '1rem' }}>
            <AlertTriangle size={48} opacity={0.2} />
            <div>No active security alerts at this time.</div>
          </div>
        )}
      </div>
    </div>
  );
}
